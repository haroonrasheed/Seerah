function bindUI() {
  langButtons.forEach((button) => {
    button.addEventListener("click", () => {
      const lang = button.dataset.lang === "ur" ? "ur" : "en";
      if (lang === currentLang) return;
      currentLang = lang;
      localStorage.setItem("seerah-lang", currentLang);
      applyLanguage();
    });
  });

  viewButtons.forEach((button) => {
    button.addEventListener("click", () => {
      const nextView = button.dataset.view === "prophets" ? "prophets" : "seerah";
      if (nextView === activeView) return;
      setActiveView(nextView, { resetMapOnSwitch: true });
    });

    button.addEventListener("keydown", (event) => {
      if (event.key !== "ArrowRight" && event.key !== "ArrowLeft" && event.key !== "Home" && event.key !== "End") {
        return;
      }

      event.preventDefault();
      const currentIndex = viewButtons.indexOf(button);
      let nextIndex = currentIndex;

      if (event.key === "ArrowRight") {
        nextIndex = (currentIndex + 1) % viewButtons.length;
      } else if (event.key === "ArrowLeft") {
        nextIndex = (currentIndex - 1 + viewButtons.length) % viewButtons.length;
      } else if (event.key === "Home") {
        nextIndex = 0;
      } else if (event.key === "End") {
        nextIndex = viewButtons.length - 1;
      }

      const nextButton = viewButtons[nextIndex];
      if (!nextButton) return;
      nextButton.focus();
      const nextView = nextButton.dataset.view === "prophets" ? "prophets" : "seerah";
      if (nextView !== activeView) {
        setActiveView(nextView, { resetMapOnSwitch: true });
      }
    });
  });

  filterButtons.forEach((button) => {
    button.addEventListener("click", () => {
      activeFilter = button.dataset.filter;
      filterButtons.forEach((btn) => btn.classList.toggle("active", btn === button));
      mapProgressOrder = null;
      mapFocusedEventIds = null;
      renderTimeline();
      updateMapVisibility({ fitMap: true });
      queueTimelineScrollSync(true);
    });
  });

  prophetFilterButtons.forEach((button) => {
    button.addEventListener("click", () => {
      const nextFilter = button.dataset.filter;
      if (!PROPHET_FILTERS.has(nextFilter)) return;
      activeProphetFilter = nextFilter;
      prophetFilterButtons.forEach((btn) => btn.classList.toggle("active", btn.dataset.filter === activeProphetFilter));
      renderProphetsTimeline();
    });
  });

  closeDialogBtn?.addEventListener("click", () => dialogEl.close());
  scrollTopBtn?.addEventListener("click", () => {
    window.scrollTo(0, 0);
  });

  focusMapBtn?.addEventListener("click", () => {
    if (!activeEventId) return;
    const event = eventById.get(activeEventId);
    if (!event) return;
    const mapPoint = mapPointById.get(event.id);
    if (!mapPoint) return;
    mapProgressOrder = event.order;
    mapFocusedEventIds = new Set([event.id]);
    updateMapVisibility({ fitMap: true });
    showMapPopup(event.id);
    pulseMapPoint(mapPoint.group);
  });

  dialogEl?.addEventListener("click", (evt) => {
    const rect = dialogEl.getBoundingClientRect();
    const isBackdrop =
      evt.clientX < rect.left || evt.clientX > rect.right || evt.clientY < rect.top || evt.clientY > rect.bottom;
    if (isBackdrop) dialogEl.close();
  });

  window.addEventListener("resize", () => {
    drawRoutePath();
    drawProphetsRoutePath();
    drawMapEventRoute();
    repositionMapPopup();
    queueTimelineScrollSync(true);
  });

  window.addEventListener(
    "scroll",
    () => {
      queueTimelineScrollSync();
    },
    { passive: true }
  );
}

function setActiveView(view, options = {}) {
  const settings = {
    skipPersist: false,
    preserveMapFrame: false,
    resetMapOnSwitch: false,
    ...options
  };

  activeView = view === "prophets" ? "prophets" : "seerah";
  if (!settings.skipPersist) {
    localStorage.setItem("seerah-view", activeView);
  }

  const isSeerahView = activeView === "seerah";
  const shouldResetMap = settings.resetMapOnSwitch && !!mapZoomLayer;
  if (shouldResetMap) {
    mapProgressOrder = null;
    mapFocusedEventIds = null;
    hideMapPopup();
    applyDefaultMapView();
  }
  viewButtons.forEach((btn) => {
    const isActive = btn.dataset.view === activeView;
    btn.classList.toggle("active", isActive);
    btn.setAttribute("aria-selected", isActive ? "true" : "false");
    btn.tabIndex = isActive ? 0 : -1;
  });

  filterWrapEl.hidden = !isSeerahView;
  prophetsFilterWrapEl.hidden = isSeerahView;
  filterWrapEl.setAttribute("aria-hidden", isSeerahView ? "false" : "true");
  prophetsFilterWrapEl.setAttribute("aria-hidden", isSeerahView ? "true" : "false");
  timelinePaneEl.hidden = !isSeerahView;
  mapPaneEl.hidden = !isSeerahView;
  prophetsPaneEl.hidden = isSeerahView;
  stageEl?.classList.toggle("view-prophets", !isSeerahView);

  if (isSeerahView) {
    renderTimeline();
    updateMapVisibility({ fitMap: !settings.preserveMapFrame && !shouldResetMap });
    requestAnimationFrame(() => {
      drawRoutePath();
      drawMapEventRoute();
      repositionMapPopup();
      if (!settings.preserveMapFrame) {
        queueTimelineScrollSync(true);
      }
    });
  } else {
    if (dialogEl?.open) dialogEl.close();
    hideMapPopup();
    renderProphetsTimeline();
    requestAnimationFrame(drawProphetsRoutePath);
  }
}

