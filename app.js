function setMapZoom(nextZoom, anchorX, anchorY) {
  const previousZoom = mapZoom;
  const clampedZoom = clamp(nextZoom, 1, 5);
  if (Math.abs(clampedZoom - previousZoom) < 0.0001) return;

  mapPanX = mapPanX + anchorX * (previousZoom - clampedZoom);
  mapPanY = mapPanY + anchorY * (previousZoom - clampedZoom);
  mapZoom = clampedZoom;
  clampMapPan();
  applyMapTransform();
}

function clampMapPan() {
  if (mapZoom <= 1) {
    mapPanX = 0;
    mapPanY = 0;
    return;
  }

  const minX = MAP_VIEW.width * (1 - mapZoom);
  const minY = MAP_VIEW.height * (1 - mapZoom);
  mapPanX = clamp(mapPanX, minX, 0);
  mapPanY = clamp(mapPanY, minY, 0);
}

function getMapBaseLayout() {
  const containerW = mapEl.clientWidth;
  const containerH = mapEl.clientHeight;
  const scale = Math.min(containerW / MAP_VIEW.width, containerH / MAP_VIEW.height);
  const offsetX = (containerW - MAP_VIEW.width * scale) / 2;
  const offsetY = (containerH - MAP_VIEW.height * scale) / 2;
  return { scale, offsetX, offsetY };
}

function screenToMapCoords(clientX, clientY) {
  const rect = mapEl.getBoundingClientRect();
  const { scale, offsetX, offsetY } = getMapBaseLayout();
  const localX = (clientX - rect.left - offsetX) / scale;
  const localY = (clientY - rect.top - offsetY) / scale;
  return {
    x: (localX - mapPanX) / mapZoom,
    y: (localY - mapPanY) / mapZoom
  };
}

function getMapViewportCenter() {
  const rect = mapEl.getBoundingClientRect();
  return screenToMapCoords(rect.left + rect.width / 2, rect.top + rect.height / 2);
}

function mapCoordsToContainer(x, y) {
  const { scale, offsetX, offsetY } = getMapBaseLayout();

  return {
    x: offsetX + (x * mapZoom + mapPanX) * scale,
    y: offsetY + (y * mapZoom + mapPanY) * scale
  };
}

