function setActiveEvent(eventId, options = {}) {
  const settings = {
    focusMap: true,
    ...options
  };

  if (activeEventId && nodeById.has(activeEventId)) {
    nodeById.get(activeEventId).classList.remove("active");
  }
  if (activeEventId && mapPointById.has(activeEventId)) {
    mapPointById.get(activeEventId).group.classList.remove("active");
  }

  activeEventId = eventId;
  const event = eventById.get(eventId);
  if (!event) return;

  const node = nodeById.get(event.id);
  if (node) node.classList.add("active");

  const mapPoint = mapPointById.get(event.id);
  if (mapPoint) {
    mapPoint.group.classList.add("active");
    if (settings.focusMap) {
      pulseMapPoint(mapPoint.group);
    }
  }
}

function updateMapVisibility(options = {}) {
  const settings = {
    fitMap: false,
    ...options
  };
  const filteredEvents = getVisibleEvents();
  const viewportEvents = getTimelineViewportEvents(filteredEvents);

  let timelineEvents;
  if (mapFocusedEventIds && mapFocusedEventIds.size) {
    timelineEvents = filteredEvents.filter((event) => mapFocusedEventIds.has(event.id));
  } else if (viewportEvents.length) {
    timelineEvents = viewportEvents;
  } else if (typeof mapProgressOrder === "number") {
    timelineEvents = filteredEvents.filter((event) => event.order <= mapProgressOrder);
  } else {
    timelineEvents = filteredEvents;
  }

  const visibleIds = new Set(timelineEvents.map((event) => event.id));

  events.forEach((event) => {
    const mapPoint = mapPointById.get(event.id);
    if (!mapPoint) return;
    mapPoint.group.classList.toggle("is-hidden", !visibleIds.has(event.id));
  });

  if (mapPopupEventId && !visibleIds.has(mapPopupEventId)) {
    hideMapPopup();
  }

  drawMapEventRoute();
  if (settings.fitMap) {
    focusMapOnVisiblePoints();
  }
}

function getTimelineViewportEvents(eventList) {
  const eventsList = Array.isArray(eventList) ? eventList : [];
  if (!eventsList.length) return [];

  const topEdge = 32;
  const bottomEdge = window.innerHeight - 32;
  return eventsList.filter((event) => {
    const node = nodeById.get(event.id);
    if (!node) return false;
    const rect = node.getBoundingClientRect();
    return rect.bottom > topEdge && rect.top < bottomEdge;
  });
}

function focusMapOnVisiblePoints() {
  if (!mapZoomLayer) return;

  const visiblePoints = events
    .filter((event) => {
      const mapPoint = mapPointById.get(event.id);
      return mapPoint && !mapPoint.group.classList.contains("is-hidden");
    })
    .map((event) => mapPointById.get(event.id));

  if (!visiblePoints.length) return;

  const xs = visiblePoints.map((pt) => pt.x);
  const ys = visiblePoints.map((pt) => pt.y);
  const minX = Math.min(...xs);
  const maxX = Math.max(...xs);
  const minY = Math.min(...ys);
  const maxY = Math.max(...ys);

  const padX = 120;
  const padY = 160;
  const width = Math.max(maxX - minX, 110);
  const height = Math.max(maxY - minY, 160);

  let nextZoom;
  if (visiblePoints.length === 1) {
    nextZoom = 3.2;
  } else {
    nextZoom = Math.min((MAP_VIEW.width - padX) / width, (MAP_VIEW.height - padY) / height);
  }
  mapZoom = clamp(nextZoom, 1.45, 4.6);

  const centerX = (minX + maxX) / 2;
  const centerY = (minY + maxY) / 2;
  const targetCenterX = MAP_VIEW.width * 0.42;
  const targetCenterY = MAP_VIEW.height * 0.52;

  mapPanX = targetCenterX - centerX * mapZoom;
  mapPanY = targetCenterY - centerY * mapZoom;
  clampMapPan();
  applyMapTransform();
}

