function drawRoutePath() {
  const visibleEvents = getVisibleEvents();
  if (!visibleEvents.length || !routeSvg || !routePathBg || !routePathDots) return;

  const timelineRect = timelineEl.getBoundingClientRect();
  const svgRect = routeSvg.getBoundingClientRect();
  const svgWidth = Math.max(svgRect.width, timelineRect.width);
  const svgHeight = Math.max(svgRect.height, timelineRect.height);

  routeSvg.setAttribute("viewBox", `0 0 ${Math.round(svgWidth)} ${Math.round(svgHeight)}`);

  const points = visibleEvents
    .map((event) => pointById.get(event.id))
    .filter(Boolean)
    .map((pointEl) => {
      const r = pointEl.getBoundingClientRect();
      return {
        x: r.left + r.width / 2 - timelineRect.left + 5,
        y: r.top + r.height / 2 - timelineRect.top + 5
      };
    });

  if (!points.length) return;

  let path = `M ${points[0].x.toFixed(1)} ${points[0].y.toFixed(1)}`;
  for (let i = 1; i < points.length; i += 1) {
    const prev = points[i - 1];
    const curr = points[i];
    const midY = (prev.y + curr.y) / 2;
    path += ` C ${prev.x.toFixed(1)} ${midY.toFixed(1)} ${curr.x.toFixed(1)} ${midY.toFixed(1)} ${curr.x.toFixed(1)} ${curr.y.toFixed(1)}`;
  }

  routePathBg.setAttribute("d", path);
  routePathDots.setAttribute("d", path);
}

function queueTimelineScrollSync(force = false) {
  if (activeView !== "seerah") return;
  if (scrollSyncRaf && !force) return;
  if (scrollSyncRaf) {
    cancelAnimationFrame(scrollSyncRaf);
  }
  scrollSyncRaf = requestAnimationFrame(() => {
    scrollSyncRaf = 0;
    syncMapWithTimelineScroll();
  });
}

function syncMapWithTimelineScroll() {
  if (activeView !== "seerah") return;
  const filteredEvents = getVisibleEvents();
  if (!filteredEvents.length) {
    mapProgressOrder = null;
    mapFocusedEventIds = null;
    updateMapVisibility({ fitMap: false });
    return;
  }

  const viewportEvents = getTimelineViewportEvents(filteredEvents);
  const candidateEvents = viewportEvents.length ? viewportEvents : filteredEvents;

  const targetY = Math.max(120, Math.min(window.innerHeight * 0.4, window.innerHeight - 140));
  let bestEvent = candidateEvents[0];
  let bestScore = Number.POSITIVE_INFINITY;

  candidateEvents.forEach((event) => {
    const node = nodeById.get(event.id);
    if (!node) return;
    const rect = node.getBoundingClientRect();
    const centerY = rect.top + rect.height / 2;
    const score = Math.abs(centerY - targetY);
    if (score < bestScore) {
      bestScore = score;
      bestEvent = event;
    }
  });

  if (!bestEvent) return;

  mapFocusedEventIds = new Set(candidateEvents.map((event) => event.id));
  mapProgressOrder = bestEvent.order;
  setActiveEvent(bestEvent.id, { focusMap: false });
  updateMapVisibility({ fitMap: false });
}

